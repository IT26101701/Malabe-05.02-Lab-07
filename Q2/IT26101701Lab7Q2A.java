import java.util.Scanner;

public class IT26101701Lab7Q2A {
	
    public static void main(String[] args) {
		
		int row, column;
		
		//Nested for loop 
		for (row = 1; row <= 4; row++ ){   //Outer for loop to control rows
			
			//Loop to print the dollar signs according to no.of rows and columns
			for (column = 1; column <= 5; column++ ){   //Inner for loop to control column
				
				System.out.print("$ ");
				
			}
			
			System.out.println ();
			
		}
	
	}
	
}